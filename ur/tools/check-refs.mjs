// کراس ریفرنس ٹیبل: متن کے اندر موجود ہر "انداراجہ X" حوالے کو اس انداراجے کے عنوان تک سلجھاتا ہے جس
// کی طرف یہ اصل میں اشارہ کرتا ہے، اور نتیجہ docs/引用对照.md میں لکھتا ہے۔ وہ فائل git میں چیک اِن
// ہوتی ہے، اس لیے جب انداراجے داخل یا حذف کرنے سے ایک حوالہ جس کی طرف اشارہ کرتا ہے وہ بدل جاتا ہے،
// تو git diff اسے براہ راست دکھاتا ہے — اگر انداراجے کا نمبر وہی ہے مگر عنوان بدل گیا ہے، تو یہ
// غلط ترتیب کا اشارہ ہے۔
//
//   node tools/check-refs.mjs            # ٹیبل دوبارہ بنائیں (sync-stats.mjs خود کار طور پر اسے کال کرتا ہے)
//   node tools/check-refs.mjs --check    # صرف تصدیق کریں، فائل نہ لکھیں؛ ٹوٹے ہوئے حوالوں پر خروج کوڈ 1 (CI کے لیے)
//   node tools/check-refs.mjs --suspect  # ان حوالوں کی فہرست بھی دیں جن کے الفاظ ہدف عنوان سے مطابقت نہیں رکھتے؛ کئی غلط مثبتیات، تاریخی صفائی کے لیے استعمال ہوتا ہے
//
// یہ کیوں ضروری ہے: انداراجے کے نمبر پوزیشن پر منحصر ہیں، اور متن کے حوالوں میں صرف پوزیشن ریکارڈ
// ہوتی ہے، مواد نہیں۔ 2026-09-19 کو سیکشن 7 میں چھ غلطیاں پائی گئیں
// (طبی امداد کا حوالہ دیباؤ کو، ریلیف سٹیشن انداراجہ غلط انداراجے کو)، جو سب
// درست انداراجہ نمبر حد کے اندر تھے، اس لیے حد سے باہر کی جانچ نے ان میں سے کسی کو بھی نہیں پکڑا۔
// نوٹ: ہمیشہ سطروں کو /\r?\n/ سے الگ کریں، کبھی '\n' سے نہیں۔ book/ کے تحت فائلوں میں سطروں کے اختتام
// میں تضاد ہے (CRLF اور LF کا مِکس)، اور JS regex . سے \r نہیں ملتا (JS میں CR بھی سطر کے اختتام کے
// طور پر شمار ہوتا ہے، Python اور Perl کے برعکس)۔ \r چھوڑنے کا مطلب ہے کہ /^### (\d+)\. (.*)$/ ایک
// CRLF فائل پر کچھ بھی نہیں ملا پائے گا۔
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK_ONLY = process.argv.includes('--check');

// ایک ترتیب کے اندر کے سادہ حوالے ("انداراجہ 8 دیکھیں") صرف ان فیلڈز میں تلاش کیے جاتے ہیں: ماخذ
// فیلڈ میں "انداراجہ N" تقریباً ہمیشہ ایک قانونی آرٹیکل کی طرف اشارہ کرتا ہے، اس لیے اسے شامل کرنا
// صرف شور ہوگا۔
const FIELDS = /^- (说人话|收益|备注|成本)：/;
// کراس سیکشن حوالے سیکشن نمبر کے ساتھ ("سیکشن 11، انداراجہ 16 دیکھیں") قانونی آرٹیکل سے ٹکرا نہیں
// کرتے، اس لیے یہاں ماخذ فیلڈ بھی اسکین کیا جاتا ہے۔
// book/26 انداراجہ 103 میں، "لاگ کی رٹینشن سیکشن 11، انداراجہ 16 دیکھیں" ماخذ فیلڈ میں لکھا گیا ہے
// اور اس کے بغیر یہ رہ جاتا۔
const CROSS_FIELDS = /^- (说人话|收益|备注|成本|来源)：/;

const files = readdirSync(resolve(ROOT, 'book')).filter(f => /^\d\d-.*\.md$/.test(f)).sort();
// docs/ کے تحت لمبے پڑھائیں بھی اسکین کی جاتی ہیں۔ سیکشن کے آغاز کے تعارف کی طرح،
// یہ لمبی اسکین کے دائرے سے باہر تھے: جب انداراجے کے نمبر بدلے گئے، --check نے اب بھی پاس اطلاع دی،
// اور کراس ریفرنس ٹیبل کا diff بھی ان حوالوں کو ظاہر نہیں کر سکا۔ 2026-09-21 کے آڈٹ
// میں، تین لمبے پڑھائیوں میں 23 "سیکشن X، انداراجہ Y" حوالے تھے، جن میں سے کبھی کسی کی بھی
// تصدیق نہیں ہوئی تھی۔
// صرف docs/ کے بالکل نیچے .md فائلیں لیں۔ ذیلی ڈائریکٹری docs/核实记录/ کو خارج کریں: یہ
// فائلیں ایک وقت میں تصدیقی عمل ریکارڈ کرتی ہیں، اور ان میں انداراجے کے نمبر تاریخی حالت ہیں اور
// متن کی پیروی نہیں کرنے چاہئیں۔ کراس ریفرنس ٹیبل خود بھی خارج کیا گیا ہے۔
const docs = readdirSync(resolve(ROOT, 'docs')).filter(f => f.endsWith('.md') && f !== '引用对照.md').sort();

// پہلے ہر سیکشن کے انداراجے کے عنوان پڑھیں: sections[سیکشن نمبر] = { file, titles: { انداراجہ نمبر: عنوان } }
const sections = new Map();
for (const f of files) {
  const num = Number(f.slice(0, 2));
  const titles = new Map();
  for (const line of readFileSync(resolve(ROOT, 'book', f), 'utf8').split(/\r?\n/)) {
    const m = /^### (\d+)\. (.*)$/.exec(line);
    if (m) titles.set(Number(m[1]), m[2].trim());
  }
  sections.set(num, { file: f, titles });
}

// ایک واحد حوالہ "انداراجے 3، 10، 11" لکھا جا سکتا ہے، جسے کئی انداراجہ نمبروں میں تقسیم کیا جاتا ہے۔
// رینج کی علامت بھی پہچانی جاتی ہے: "انداراجے 11 تا 14" / "انداراجے 5 تا 10"۔ ایسی عبارت
// پہلے بالکل نہیں مل پاتی تھی اور عملاً غیر اسکین شدہ رہ جاتی تھی؛ کتاب میں 5 ایسی جگہیں ہیں۔
const RANGE = /^\s*(\d+)\s*(?:到|至)\s*第?\s*(\d+)\s*$/;
// [انداراجہ نمبر، رینج سے ہے] لوٹاتا ہے۔ رینج کا مطلب مسلسل انداراجوں کا بلاک ہے (مثلاً،
// "غصہ نکالنے کے انداراجے"، "پلیٹ فارم ذمہ داری کے انداراجے")، جہاں بلاک میں ہر انداراجے کو
// اپنا انکر نہیں دیا جا سکتا، اس لیے رینج سے پھیلے ہوئے انداراجہ نمبر انکر کی تصدیق چھوڑ دیتے ہیں —
// یہ اب بھی ٹیبل میں جاتے ہیں، اور تبدیلیاں diff میں عنوان کی تبدیلی سے پکڑی جاتی ہیں۔
const nums = s => {
  const out = [];
  for (const part of s.split(/[、,]/)) {
    const r = RANGE.exec(part);
    if (r) {
      const [a, b] = [Number(r[1]), Number(r[2])];
      if (b >= a && b - a <= 30) for (let i = a; i <= b; i++) out.push([i, true]);
      continue;
    }
    const n = Number(part.trim());
    if (Number.isFinite(n)) out.push([n, false]);
  }
  return out;
};
// انداراجہ نمبر حصے کے لیے پیٹرن: "3", "3,10", "11 تا 14", "5 تا 10"
const SPEC = '[\\d、,\\s]+?(?:(?:到|至)\\s*第?\\s*\\d+)?';

const out = [];
const problems = [];
const suspects = [];
const weak = [];
let total = 0;

// اسکین یونٹ: book/ کے تحت ہر سیکشن کے لیے ایک، docs/ کے تحت ہر لمبی پڑھائی کے لیے ایک۔
const targets = [
  ...files.map(f => ({ f, dir: 'book', isDoc: false })),
  ...docs.map(f => ({ f, dir: 'docs', isDoc: true })),
];

for (const { f, dir, isDoc } of targets) {
  const num = isDoc ? 0 : Number(f.slice(0, 2));
  const self = isDoc ? null : sections.get(num);
  const lines = readFileSync(resolve(ROOT, dir, f), 'utf8').split(/\r?\n/);
  const rows = [];
  // cur موجودہ انداراجے کا نمبر ہے؛ 0 کا مطلب ہے ابھی تک ہم انداراجے میں داخل نہیں ہوئے
  // (book کے سیکشن آغاز کا تعارف، یا docs میں کوئی بھی پوزیشن)۔
  // unit "ماخذ" کالم میں دکھایا گیا نام ہے: انداراجوں کو "انداراجہ N" لیبل کیا جاتا ہے، سیکشن
  // آغاز کو "صدرِ ترتیب" (section opener) لیبل کیا جاتا ہے، اور لمبی پڑھائیاں حالیہ سب ہیڈنگ استعمال کرتی ہیں۔
  let cur = 0;
  let unit = isDoc ? 'ابتدا' : 'صدرِ ترتیب';

  // حوالے سے پہلے والا جملہ اکثر بیان کرتا ہے کہ یہ کس کی طرف اشارہ کرتا ہے ("طبی امداد (انداراجہ 11
  // دیکھیں)")؛ پورا جملہ شامل کیا جاتا ہے تاکہ ٹیبل دیکھنے والا ایک انسان متن میں واپس جائے بغیر
  // فیصلہ کر سکے کہ حوالہ درست ہے یا نہیں۔
  // مقررہ کریکٹرز کی بجائے حالیہ رمز اوقاف تک کاٹیں — ایک مقررہ 14 کریکٹرز نے کبھی کئی درست
  // حوالوں کو مشکوک بنا دیا تھا ("一氧化碳见第 18 条،烧烫伤见第 13 条" کو "氧化碳" تک کاٹ دیا گیا تھا
  // جو "烫伤" کے سامنے تھا)۔
  const ctxOf = (line, idx) => {
    const before = line.slice(0, idx);
    let start = -1;
    for (const p of ['。', '؛', '!', '؟', ':']) start = Math.max(start, before.lastIndexOf(p));
    return before.slice(start + 1).slice(-44).replace(/\|/g, '｜');
  };
  // انکر کی تصدیق کے لیے استعمال ہونے والی ونڈو اوپر والی سے تنگ ہے: صرف وہ کاما سے الگ کیا گیا
  // جملہ جس میں حوالہ موجود ہے۔ پورے جملے جیتی چوڑائی ونڈو میں، عام الفاظ جیسے
  // "自己" (خود) اور "公司" (کمپنی) اتفاق سے دوسرے انداراجے کے عنوان سے مل سکتے ہیں، جس سے جعلی
  // انکر بن جاتے ہیں — 2026-09-20 کو سیکشن 31 میں ایک انداراجہ داخل کیا گیا اور انداراجہ 1 کے نوٹ میں
  // "…的贷款见本节第 15 条" کو نئے انداراجے "在家给境外公司远程干活……个税自己报"
  // (بیرونی کمپنی کے لیے دور دراز کام کرنا، اپنی انکم ٹیکس خود داخل کرنا) پر منتقل کر دیا گیا۔ پورے جملے کی
  // ونڈو میں، دو کاموں کے باہر "你自己还" نے عنوان میں "个税自己报" سے ٹکرایا، اور --check نے پاس اطلاع دی۔
  // جب جملہ بہت مختصر ہو ("……، انداراجہ 11 دیکھیں" ونڈو ایک "دیکھیں" تک کم ہو جائے)،
  // تو ایک جملہ مزید پیچھے ہٹیں؛ ورنہ ایک درست حوالے کو سادہ انداراجہ نمبر سمجھا جائے گا۔
  // وہ رموز اوقاف جو جملے کی حد نہیں سمجھے جاتے: 顿号 (چینی تعداد کا کاما "、")،
  // کوٹیشن مارکس، قوسین۔ "含糖饮料、加工肉（本节第 3 条）" میں انکر 顿号 کے پار بیٹھا ہے؛
  // "为『比别人强一档』而加的预算见本节第 24 条" میں انکر کوٹیشن مارکس کے اندر ہے؛ وہاں کاٹنا
  // غلط مثبتیات کا باعث بنتا۔
  const CLAUSE = ['。', '；', '！', '？', '：', '，'];
  const narrowOf = (line, idx) => {
    const before = line.slice(0, idx);
    const cut = s => {
      let start = -1;
      for (const p of CLAUSE) start = Math.max(start, s.lastIndexOf(p));
      return { head: s.slice(0, start + 1), tail: s.slice(start + 1) };
    };
    const last = cut(before);
    if (last.tail.replace(/[见按同和依据参照的在]/g, '').length >= 4) return last.tail.slice(-24);
    return (cut(last.head.slice(0, -1)).tail + last.tail).slice(-24);
  };
  // حوالے کے بعد کا متن بھی انکر کا حساب ہوتا ہے: "انداراجہ 16 (IOU اور گارنٹی)" کلید لفظ کو
  // انداراجہ نمبر کے بعد رکھتا ہے۔ حوالے کے بعد پہلے رمز اوقاف تک (زیادہ سے زیادہ 40 کریکٹرز) لیں۔
  // مقررہ کریکٹرز کی تعداد استعمال نہیں کی جا سکتی: "سیکشن 1، انداراجے 7، 8،
  // 14، 17، 18، 19، 23، 24، 29 دیکھیں (بلڈ پریشر، بلڈ شوگر، …)" — ایسی طویل انداراجہ نمبر فہرستیں
  // تشریح کو ونڈو سے باہر دھکیل دیتی ہیں۔
  const afterOf = (line, idx) => {
    const rest = line.slice(idx).replace(new RegExp(`^第\\s*\\d+\\s*节?第?\\s*(?:${SPEC})?\\s*条`), '');
    const end = rest.search(/[。；！？]/);
    return (end === -1 ? rest : rest.slice(0, end)).slice(0, 40).replace(/\|/g, '｜');
  };

  lines.forEach((line, i) => {
    if (isDoc) {
      const h = /^#{1,6}\s+(.+?)\s*$/.exec(line);
      if (h) { unit = h[1].slice(0, 24); return; }
    } else {
      const t = /^### (\d+)\. (.*)$/.exec(line);
      if (t) { cur = Number(t[1]); unit = `انداراجہ ${cur}`; return; }
    }
    // انداراجے کی تفصیلات صرف ان مخصوص فیلڈز میں اسکین کی جاتی ہیں (ماخذ فیلڈ میں "انداراجہ N" کے
    // ذکر زیادہ تر قانونی آرٹیکل نمبر ہیں)۔ سیکشن آغاز کے تعارفات اور لمبی پڑھائی کا
    // متن عام پیراگراف ہیں جو فیلڈ پریفکس سے نہیں ملتے، اس لیے پوری سطر چھوڑ دی جاتی ہے — اسی طرح
    // یہ پہلے خاموشی سے چھوڑ دیے جاتے تھے۔
    const inEntry = !isDoc && cur > 0;
    if (inEntry ? !CROSS_FIELDS.test(line) : !line.trim()) return;

    // رشتہ دار پوائنٹرز ("اگلا انداراجہ دیکھیں"، "سزا پچھلا انداراجہ دیکھیں") مکمل طور پر ممنوع ہیں:
    // ان میں کوئی انداراجہ نمبر نہیں ہوتا، اس لیے ایک انداراجہ داخل کرنے سے یہ سب کے ساتھ ساتھ سلائیڈ
    // ہو جاتے ہیں، کراس ریفرنس ٹیبل میں diff تبدیلی کو نہیں پکڑ سکتا، اور --check کی سادہ انداراجہ
    // نمبر چھان بھی انہیں اسکین نہیں کر سکتی۔ 2026-09-20 کو ایک ہی اسکین نے تین ایسے پکڑے جو
    // لمبے عرصے سے غلط تھے: HPV ویکسین انداراجے کا "اگلا انداراجہ دیکھیں" بریسٹ کینسر اسکریننگ کو
    // اشارہ کرتا تھا (اسے سروائیکل کینسر اسکریننگ کو اشارہ کرنا چاہیے تھا)، دھمکی انداراجے کا "سزا پچھلا
    // انداراجہ دیکھیں" 念頭条 (آراء کے انداراجے) کو اشارہ کرتا تھا، اور بے روزگاری رجسٹریشن
    // انداراجے کا "پچھلا انداراجہ: رضاکارانہ استعفیٰ نہ کریں" ثبوت محفوظ کرنے کے
    // انداراجے کو اشارہ کرتا تھا۔ غلط ہٹ جیسے "最后一条" (آخری انداراجہ)، "之后一条腿" (ایک ٹانگ بعد) کو خارج کریں۔
    for (const m of line.matchAll(/(?<![最之以])(上一条|下一条|前一条|后一条|上面那条|上面这条|前面那条)/g)) {
      problems.push(`${f}:${i + 1} ${unit} نے رشتہ دار پوائنٹر "${m[1]}" استعمال کیا — "انداراجہ N (انکر لفظ)" میں بدلیں`);
    }

    // کراس سیکشن: سیکشن N، انداراجہ X
    for (const m of line.matchAll(new RegExp(`第\\s*(\\d+)\\s*节第\\s*(${SPEC})\\s*条`, 'g'))) {
      const target = sections.get(Number(m[1]));
      for (const [x, range] of nums(m[2])) {
        const title = target?.titles.get(x);
        rows.push({ from: unit, range, ref: `صدر ${m[1]}، انداراجہ ${x}`, title, line: i + 1, ctx: ctxOf(line, m.index), narrow: narrowOf(line, m.index), after: afterOf(line, m.index) });
        if (!title) problems.push(`${f}:${i + 1} ${unit} "صدر ${m[1]}، انداراجہ ${x}" کی طرف اشارہ کرتا ہے — اس سیکشن میں ایسا کوئی انداراجہ نہیں`);
      }
    }

    // لمبی پڑھائیوں میں "یہ سیکشن" کا تصور نہیں ہے؛ لمبی پڑھائی میں سادہ "انداراجہ N" ایک
    // قانونی آرٹیکل کی طرف اشارہ کرتا ہے، اس لیے اسکین نہیں کیا جاتا۔
    if (isDoc) return;

    // ترتیب کے اندر: تمام "انداراجہ X" ذکر کو تعارفی لفظ سے قطع نظر اسکین کریں — متن میں
    // "انداراجہ X دیکھیں" سے کہیں زیادہ استعمال ہیں، مثلاً، "انداراجہ 1 کے مطابق چھاتی دبائیں"، "فیصلہ کا طریقہ انداراجہ 4 جیسا"،
    // "پہلے انداراجہ 8 سے چیک کریں"، "انداراجہ 4 میں سے ایک چنیں"۔ پچھلے ورژن صرف
    // تین تعارفی الفاظ پہچانتے تھے اور ان سب کو چھوڑ دیتے تھے۔ ماخذ فیلڈ بالکل اسکین نہیں ہوتی
    // (یہ قانونی آرٹیکل نمبروں سے بھری ہے)۔
    // سیکشن آغاز کے تعارفات فیلڈ کی پابندی سے مستثنیٰ نہیں ہیں: وہاں "انداراجہ N"
    // پڑھنے کی رہنمائی ہے ("انداراجہ 9 پیسے کے بارے میں ہے"، "انداراجہ 2 پڑھنے اور عمر کے بارے میں ہے")، اور
    // داخلے کی وجہ سے یہ بھی بدل سکتا ہے؛ یہ بھی ٹیبل میں جاتا ہے۔
    if (inEntry && !FIELDS.test(line)) return;
    const stripped = line.replace(new RegExp(`第\\s*\\d+\\s*节第\\s*${SPEC}\\s*条`, 'g'), '');
    for (const m of stripped.matchAll(new RegExp(`第\\s*(${SPEC})\\s*条`, 'g'))) {
      // فیصلہ کریں کہ یہ قانونی آرٹیکل ہے یا انداراجہ کا حوالہ۔ 2026-09-21 سے پہلے
      // طریقہ یہ تھا کہ چیک کریں کہ آیا پچھلے 16 کریکٹرز میں "法" (قانون) ہے، مگر "办法"
      // (اقدام)، "查法" (چیک کرنے کا طریقہ)، "法律援助" (قانونی امداد)، اور "违法解除" (غیر قانونی
      // برطرفی) سب میں "法" ہے، اور کئی حقیقی حوالوں کا ایک بڑا بچہ نقصان کے طور پر چھوڑ دیا گیا۔
      // بدتر یہ کہ چھوڑنا خاموش تھا: ایسے حوالے ٹیبل میں بالکل داخل نہیں ہوتے تھے،
      // اس لیے --check کے پاس چیک کرنے کے لیے کچھ نہیں تھا اور "پاس" اطلاع دیتا تھا؛ صرف کل حوالہ
      // گنتی میں کمی اسے ظاہر کرتی۔ ایک مکمل اسکین نے کبھی 12 ایسے حوالے پکڑے۔
      // موجودہ منطق دو واضح معیاروں پر مبنی چھوڑتی ہے:
      //   ① "انداراجہ N" کے فوراً متصل ایک حوالہ نشان ہے — 《…》、〔…〕、"14 号" (نمبر 14)،
      //      "该解释" (یہ تشریح)، یا ایک قانونی نام کے ساتھ ختم ہونے والا سلسلہ (مثلاً،
      //      "治安管理处罚法第 26 条" (پبلک سیکیورٹی ایڈمنسٹریشن پنشمنٹ لاء کا آرٹیکل 26))؛
      // صرف "فوراً متصل" پہچانا جاتا ہے، پچھلے N کریکٹرز کی مبہم ونڈو نہیں،
      // اور "کیا یہ جملے کے آغاز میں ہے" بھی معیار کے طور پر استعمال نہیں ہوتا — انداراجہ حوالے بھی
      // جملے کے آغاز میں ظاہر ہوتے ہیں ("انداراجہ 4 کا ریلیف سٹیشن مفت کھانا اور پناہ دیتا ہے"، "انداراجہ 7 میں
      // 'ابھی ہسپتال جائیں' کی فہرست")۔ اس کا خرچ یہ ہے کہ قانونی حوالوں کو اپنا قانونی نام لے کر
      // چلنا پڑتا ہے: جب ایک سطر میں ایک قانون درج کریں، تو "该解释第 11 条" لکھیں
      // (اس تشریح کا آرٹیکل 11)، نہ کہ "… کورٹ آرڈر۔ آرٹیکل 11 ثبوت جمع کرنے کے بارے میں ہے"
      // جو پچھلے جملے پر انحصار کرے۔ یہ متن کی خود کفالت کا
      // تقاضہ پہلے سے تھا۔
      const tail = stripped.slice(0, m.index).replace(/\s+$/, '');
      const CITE = /(《[^》]*》|〔[^〕]*〕|\d+\s*号|该(?:解释|意见|办法|规定|条例|通知|法)|[^\s，。；：、（）「」]{0,8}(?:法|条例|办法|规定|准则|细则|公约))$/;
      if (CITE.test(tail)) continue;
      for (const [x, range] of nums(m[1])) {
        const title = self.titles.get(x);
        rows.push({ from: unit, range, ref: `اس ترتیب کا انداراجہ ${x}`, title, line: i + 1, ctx: ctxOf(stripped, m.index), narrow: narrowOf(stripped, m.index), after: afterOf(stripped, m.index) });
        // ترتیب کے اندر حوالے جو اس ترتیب کی انداراجہ گنتی سے تجاوز کرتے ہیں عموماً قانونی
        // آرٹیکل نمبر ہیں جو انداراجہ حوالے کے طور پر غلط شناخت ہوئے؛ انہیں انسانی جائزے کے لیے درج کریں۔
        if (!title) problems.push(`${f}:${i + 1} ${unit} "انداراجہ ${x}" کی طرف اشارہ کرتا ہے — اس ترتیب میں صرف ${self.titles.size} انداراجے ہیں (ممکنہ طور پر ایک قانونی آرٹیکل نمبر)`);
        if (inEntry && x === cur) problems.push(`${f}:${i + 1} انداراجہ ${cur} خود اپنی طرف اشارہ کرتا ہے`);
      }
    }
  });

  // کیا اس حوالے کو خود کار طور پر درست تصدیق کیا جا سکتا ہے: حوالے سے پہلے اور بعد کے متن میں،
  // کیا ایسا سپین ہے جو ہدف انداراجے کے عنوان میں بھی ظاہر ہوتا ہے؟ ہاں → حوالہ ایک انکر رکھتا ہے
  // اور غلط ترتیب نوٹس کی جائے گی؛ نہیں → یہ ایک سادہ انداراجہ نمبر ہے ("اصل
  // الگورتھم انداراجہ 34 میں مل سکتا ہے")، اور غلط ترتیب کا پتہ نہیں لگایا جا سکتا — ایک واضح
  // تشریح کی ضرورت ہے۔
  // دو کریکٹرز کا اتفاق بہت آسان ہے ("自己" (خود)، "公司" (کمپنی)، "时间"
  // (وقت))، اس لیے انکر کی طاقت لمبائی اور فاصلے کے لحاظ سے درجہ بند ہے:
  // پورے جملے میں تین مسلسل کریکٹرز کا ملنا ("含糖饮料" (میٹھے مشروبات)، "居民医保"
  // (ریذیڈنٹ میڈیکل انشورنس)) ایک مضبوط انکر شمار ہوتا ہے؛ دو کریکٹرز کے ملنے کے لیے، انہیں
  // حوالہ رکھنے والے کاما سے الگ کیے گئے جملے کے اندر ہونا چاہیے۔ دو کاموں کے پار بیٹھا "你自己还"
  // جو عنوان میں "个税自己报" سے ٹکرایا وہی تھا جس نے 2026-09-20 کی تبدیلی کو پار ہونے دیا۔
  const longest = (text, title) => {
    let best = 0;
    for (let i = 0; i < text.length; i++) {
      for (let n = 1; i + n <= text.length; n++) {
        const seg = text.slice(i, i + n);
        if (!/^[一-龥]+$/.test(seg)) break;
        if (!title.includes(seg)) break;
        best = Math.max(best, n);
      }
    }
    return best;
  };
  // ہندسے اور لاطینی حروف کے سلسلے بھی انکر کے طور پر شمار ہوتے ہیں: 12356، AED، CT، BMI، LPR اکثر بالکل
  // وہی ہوتے ہیں جس کی طرف حوالہ اشارہ کرتا ہے۔
  const token = (text, title) => (text.match(/[0-9A-Za-z]{2,}/g) ?? []).some(t => title.includes(t));
  for (const r of rows) {
    if (!r.title || r.range) continue;
    const wide = r.ctx + r.after;
    if (token(wide, r.title) || longest(wide, r.title) >= 3) continue;
    if (longest(r.narrow + r.after, r.title) >= 2) continue;
    // دو کریکٹرز کا صرف جملے کے باہر ملنا: کمزور انکر کے طور پر الگ سے درج ہیں؛ اصلاح
    // سادہ انداراجہ نمبروں جیسی ہے — ایک واضح تشریح شامل کریں۔
    const list = longest(wide, r.title) >= 2 ? weak : suspects;
    list.push(`${f}:${r.line} ${r.from} → "${r.ref}" ${r.title.slice(0, 20)}…　…${r.ctx}【${r.ref}】${r.after}…`);
  }

  if (!rows.length) continue;
  total += rows.length;
  out.push(`## ${isDoc ? 'docs/' : ''}${basename(f, '.md')}\n`);
  out.push('| ماخذ | حوالہ | جس انداراجے کی طرف اشارہ ہے | حوالے پر سیاق و سباق |');
  out.push('| --- | --- | --- | --- |');
  for (const r of rows) {
    const title = r.title ? r.title : '**ایسا انداراجہ موجود نہیں جس کی طرف اشارہ ہو**';
    out.push(`| ${r.from} | ${r.ref} | ${title} | …${r.ctx}… |`);
  }
  out.push('');
}

